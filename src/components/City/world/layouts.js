const MOVE = {
  camii: { cm_ak1: [2.6, 6.6], cm_ak2: [-2.6, 6.6], cm_clk: [5.5, 7] },
  belediye: {},
};
export function gameVenue(key, moveKey = key) {
  const v = VENUES[key];
  const mv = MOVE[moveKey] || {};
  return { ...v, items: v.items.filter((d) => d.k !== 'doordeco').map((d) => (mv[d.i] ? { ...d, x: mv[d.i][0], z: mv[d.i][1] } : d)) };
}
